#!/usr/bin/env node
/**
 * approved-source index + teacher deployment manifest -> gas/ApprovedActiveCatalog.gs
 * (the ONLY cartridge list the single Project A GAS consults at runtime for
 * approved content; GAS never reads GitHub). Metadata only; no question text.
 *   node build_active_catalog.mjs [--index f] [--deployment f] [--out f] [--check] [--content-commit <40-hex>]
 * 40-6BP: --content-commit declares contentSource GITHUB_RAW_PINNED_V1 (public QBank runtime packages pinned to that
 * commit) so the RELEASE ships NO embedded content; without it the output is byte-identical to before.
 */
import {readFileSync, writeFileSync, existsSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {activeApprovedCatalog} from './approved_catalog_normalizer.mjs';
import {withContentSource, RUNTIME_REPO} from './qa_preview.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : d; };
const index = JSON.parse(readFileSync(opt('--index', join(here, 'generated/approved-source-index.json')), 'utf8'));
const deployment = JSON.parse(readFileSync(opt('--deployment', join(here, 'deployment/active-deployment.json')), 'utf8'));
const out = opt('--out', join(here, '..', 'gas', 'ApprovedActiveCatalog.gs'));
export function renderGs(active) {
  const body = JSON.stringify(active, null, 1).replace(/</g, '\\u003c');
  return '/* GENERATED by approved-catalog/build_active_catalog.mjs — do not edit by hand.\n' +
    ' * Approved-source index + teacher deployment manifest -> active catalog.\n' +
    ' * Approval is not deployment: only explicitly deployment-approved, SHA-pinned ids. */\n' +
    'var HOJA_APPROVED_ACTIVE_CATALOG_=Object.freeze(' + body + ');\n';
}
const active = activeApprovedCatalog(index, deployment);
// F1: an active (deployed) id must have a READY content package; pin its digest too.
const report = JSON.parse(readFileSync(join(here, 'generated/approved-content-report.json'), 'utf8'));
if (report.sourceCommit !== index.sourceCommit) { console.error('CONTENT_REPORT_SOURCE_MISMATCH'); process.exit(1); }
for (const e of active.entries) {
  const r = report.entries.find(x => x.cartridgeId === e.cartridgeId);
  if (!r || r.status !== 'READY') { console.error('ACTIVE_ID_CONTENT_NOT_READY:' + e.cartridgeId); process.exit(1); }
  e.packageSha256 = r.packageSha256;
}
active.buildType = 'RELEASE';
const cc = opt('--content-commit');
if (cc && !/^[a-f0-9]{40}$/.test(cc)) { console.error('CONTENT_COMMIT_MUST_BE_40_HEX'); process.exit(1); }
const text = renderGs(cc ? withContentSource(active, {repo: RUNTIME_REPO, commit: cc}) : active);
if (args.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== text) { console.error('DRIFT ApprovedActiveCatalog.gs'); process.exit(1); }
} else writeFileSync(out, text);
console.log(JSON.stringify({approvedUnits: index.approvalUnits, activeEntries: active.entries.length,
  deploymentId: active.deploymentId, sourceCommit: active.sourceCommit, mode: args.includes('--check') ? 'CHECK_PASS' : 'WRITTEN'}));
