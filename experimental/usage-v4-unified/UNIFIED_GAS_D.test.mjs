const CLIENT = readFileSync(GAS_DIR + '/UsageTelemetryClient.html', 'utf8')
  .replace(/^\s*<script id="hojaProdUsageTelemetry">/, '').replace(/<\/script>\s*$/, '');
function client(w, {fault = () => null, storage = new Map(), cartridges = ['101']} = {}) {
  const calls = [];
  const env = {setTimeout: (f) => setImmediate(f), Promise, Math, JSON, Date, String, Error, Set, Object, Array};
  env.window = env;
  env.localStorage = {getItem: k => storage.has(k) ? storage.get(k) : null, setItem: (k, v) => storage.set(k, String(v))};
  env.crypto = {randomUUID};
  env.HOJA_B_LIVE = {sources: cartridges.map(c => ({data: {cartridgeId: c}}))};
  const runner = (ok, fail) => ({
    withSuccessHandler: f => runner(f, fail), withFailureHandler: f => runner(ok, f),
    recordUsageStartU1(p) {
      const n = calls.push(p.eventId);
      setImmediate(() => {
        const f = fault(n, p);
        if (f && f.before) return fail({message: f.before});
        let r;
        try { r = w.rpc('recordUsageStartU1', p); } catch (e) { return fail({message: e.message}); }
        if (f && f.lostReply) return fail({message: 'NetworkError: connection reset'});
        ok(r);
      });
    }});
  env.google = {script: {run: runner(() => {}, () => {})}};
  runInContext(CLIENT, createContext(env));
  return {api: env.HOJA_USAGE, calls, storage};
}
const settle = async (api, n) => { for (let i = 0; i < 20000; i++) { const s = api.status(); if (s.delivered + s.permanent >= n && s.queued === 0) return s; await new Promise(r => setImmediate(r)); } return api.status(); };

test('D client: 40 concurrent starts under lock timeouts, Sheets 429 and lost replies -> 40/40, 0 duplicates, 0 loss', async () => {
  const w = world();
  w.rpc('hojaListPublicCartridges');
  // Deterministic fault mix on the first 120 server calls (real R6 saw 13 lock + 17 x 429 of 40).
  const fault = n => n > 120 ? null : n % 4 === 1 ? {before: 'Exception: USAGE_APPEND_LOCK_TIMEOUT'} :
    n % 4 === 2 ? {before: 'Exception: SHEETS_HTTP_429_RATE_LIMIT_EXCEEDED'} : n % 7 === 0 ? {lostReply: true} : null;
  const c = client(w, {fault});
  const before = w.ev.getLastRow();
  assert.equal(w.stats().code, 'NOT_CONFIGURED', 'watermark not initialised before the first write');
  for (let i = 0; i < 40; i++) c.api.track('SOLO', 1);
  const s = await settle(c.api, 40);
  const added = w.ev.rows.slice(before).map(r => r[0]);
  assert.equal(s.tracked, 40);
  assert.equal(s.delivered, 40);
  assert.equal(added.length, 40, 'rows added');
  assert.equal(new Set(added).size, 40, 'no duplicate rows');
  assert.equal(w.W(), before + 40, 'watermark');
  assert.equal(w.stats().totals.all, 6 + 40, 'public total = 6 unique fixture plays + 40');
  assert.ok(s.retries > 0 && s.duplicateIgnored > 0, JSON.stringify(s));
  assert.equal(s.queued, 0);
  assert.equal(c.storage.get('hoja_usage_pending_v1'), '[]');
});
test('D client: permanent errors are not retried; transient exhaustion is queued and recovered on next load (same day)', async () => {
  const w = world();
  // permanent: unknown cartridge -> exactly one server call
  const p = client(w, {cartridges: ['999']});
  p.api.track('SOLO', 1);
  const ps = await settle(p.api, 1);
  assert.equal(ps.permanent, 1);
  assert.equal(p.calls.length, 1);
  // transient forever -> 6 attempts each, then persisted
  const storage = new Map();
  const down = client(w, {storage, fault: () => ({before: 'Exception: SHEETS_HTTP_429_RATE_LIMIT_EXCEEDED'})});
  const before = w.ev.getLastRow();
  for (let i = 0; i < 3; i++) down.api.track('SOLO', 1);
  for (let i = 0; i < 2000 && down.calls.length < 18; i++) await new Promise(r => setImmediate(r));
  await new Promise(r => setImmediate(r));
  assert.equal(down.calls.length, 18);
  assert.equal(JSON.parse(storage.get('hoja_usage_pending_v1')).length, 3);
  assert.equal(w.ev.getLastRow(), before);
  // "reload" with the same localStorage and a healthy server
  const up = client(w, {storage});
  await up.api.flush();
  assert.equal(up.api.status().delivered, 3);
  assert.equal(w.ev.getLastRow(), before + 3);
  assert.equal(new Set(w.ev.rows.slice(before).map(r => r[0])).size, 3);
  assert.equal(storage.get('hoja_usage_pending_v1'), '[]');
  // a previous day's undelivered start is dropped (it can no longer be dated correctly), never sent
  storage.set('hoja_usage_pending_v1', JSON.stringify([{day: '2000-01-01', payload: legacy(id(6000))}]));
  const later = client(w, {storage});
  await later.api.flush();
  assert.equal(later.api.status().expired, 1);
  assert.equal(later.calls.length, 0);
});
