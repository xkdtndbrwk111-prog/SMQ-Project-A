#!/usr/bin/env node
/**
 * F2: generate HOJA_RENDERER_MATH_EXT.js from the APPROVED math review HTML (pinned SHA).
 * Only the display logic is reused, byte-for-byte: `enhanceMath()` from
 * <script id="hoja-math-priority-and-notation-v1"> and `rebuildOptions()` from
 * <script id="hoja-math-teacher-final-wrap-v4">, plus the CSS rules that style what they create.
 * The approved reviewer-sidebar code and its DATA mutation (teacher C, already applied to the
 * package tags by the packager) are NOT copied. Gated to questions whose rendererQuestion
 * carries displayProfile "math-reviewfix1-ui4" so no other subject is touched.
 *   node extract_math_display.mjs --qbank <HOJA-QUESTION-BANK checkout> [--check]
 */
import {readFileSync, writeFileSync, existsSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const qbank = args[args.indexOf('--qbank') + 1];
const REL = 'approved/math/grade5-6/semester2/HOJA_MATH_187_APPROVED_REVIEW_UI4_20261122.html';
const sha = s => createHash('sha256').update(s).digest('hex');
const fail = m => { console.error(m); process.exit(1); };
const html = readFileSync(join(qbank, REL), 'utf8');
const manifest = JSON.parse(readFileSync(join(qbank, 'approved/math/manifest.json'), 'utf8'));
if (sha(html) !== manifest.reviewerSha256) fail('MATH_REVIEW_HTML_SHA_MISMATCH');
const script = id => { const i = html.indexOf('<script id="' + id + '">'); const j = html.indexOf('</script>', i); if (i < 0 || j < 0) fail('NO_SCRIPT ' + id); return html.slice(i, j); };
const slice = (src, start, end) => { const i = src.indexOf(start), j = src.indexOf(end, i); if (i < 0 || j < 0) fail('ANCHOR ' + start); return src.slice(i, j).trimEnd(); };
const s1 = script('hoja-math-priority-and-notation-v1'), s4 = script('hoja-math-teacher-final-wrap-v4');
const enhance = slice(s1, 'function enhanceMath(){', '\n const original=renderQuestion;');
const rebuild = slice(s4, 'function rebuildOptions(){', '\n const previous=renderQuestion;');
const css = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map(m => m[1]).join('\n');
const rules = (css.replace(/\/\*[\s\S]*?\*\//g, '').match(/[^{}]+\{[^{}]*\}/g) || [])
  .map(r => r.trim()).filter(r => /hoja-frac|hoja-inline-math|hoja-component|hoja-four-value|hoja-math|math-grid|math-part|math-review/.test(r));
const out = `/* GENERATED by extract_math_display.mjs — do not edit by hand.
 * Source: HOJA-QUESTION-BANK ${REL} (sha256 ${sha(html)}),
 * scripts hoja-math-priority-and-notation-v1 (sha256 ${sha(s1)}) and hoja-math-teacher-final-wrap-v4 (sha256 ${sha(s4)}).
 * enhanceMath() and rebuildOptions() below are copied verbatim; ${rules.length} CSS rules copied verbatim.
 * Applies ONLY when the current question has displayProfile === 'math-reviewfix1-ui4'. */
(function(){
 'use strict';
 if(window.HOJA_RENDERER_MATH_EXT)return;
 const style=document.createElement('style');style.id='hojaMathExtStyle';
 style.textContent=${JSON.stringify(rules.join('\n'))};
 document.head.append(style);
 const isMath=()=>{const q=typeof current==='function'?current():null;return !!(q&&q.displayProfile==='math-reviewfix1-ui4');};
 ${enhance}
 const asUnit = () => (typeof current === 'function' ? current()?.id : null);
 ${rebuild}
 const clear=()=>{const s=document.getElementById('screen');if(s){delete s.dataset.mathGridChoice;delete s.dataset.mathPartGrid;delete s.dataset.mathReviewLines;}};
 const baseRender=renderQuestion;
 renderQuestion=function(){clear();baseRender();if(isMath()){enhanceMath();rebuildOptions();}};
 const baseFeedback=setFeedback;
 setFeedback=function(q){baseFeedback(q);if(isMath())enhanceMath();};
 window.HOJA_RENDERER_MATH_EXT=Object.freeze({version:1,source:${JSON.stringify(sha(html))}});
})();
`;
const target = join(here, 'HOJA_RENDERER_MATH_EXT.js');
if (args.includes('--check')) { if (!existsSync(target) || readFileSync(target, 'utf8') !== out) fail('DRIFT HOJA_RENDERER_MATH_EXT.js'); }
else writeFileSync(target, out);
console.log(JSON.stringify({sourceSha256: sha(html), cssRules: rules.length, extSha256: sha(out), mode: args.includes('--check') ? 'CHECK_PASS' : 'WRITTEN'}));
